def gen_seq_a(x):
    # Ініціалізуємо лічильник k значенням 1 (початок послідовності)
    k = 1
    # Базовий випадок: перший елемент x_1 = x^1 / 1 = x
    current_x = x

    # Нескінченний цикл для генерації послідовності
    while True:
        # Повертаємо поточний елемент і призупиняємо виконання
        yield current_x
        # Збільшуємо лічильник кроків
        k += 1
        # Обчислюємо наступний член за виведеним рекурентним співвідношенням
        current_x = current_x * x * (k - 1) / k


# Програма обчислення необхідного члена
x_val = 2.0  # Задане значення x
k_target = 5  # Задане значення k

# Створюємо об'єкт генератора
generator_a = gen_seq_a(x_val)

# Використовуємо цикл з лічильником для досягнення k-го елемента
for i in range(k_target):
    # Отримуємо наступне значення з генератора
    result_a = next(generator_a)

# Виводимо результат
print(f"Завдання a: x_{k_target} = {result_a}")